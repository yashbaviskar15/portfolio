/**
 * Auto-detect browser/regional locale from navigator
 */
export function detectBrowserLocale(): LocaleCode {
  if (typeof window === 'undefined' || typeof navigator === 'undefined') {
    return 'en';
  }

  const rawLanguages = navigator.languages || [navigator.language || 'en'];

  for (const lang of rawLanguages) {
    const clean = lang.toLowerCase().trim();
    if (clean.startsWith('hi')) return 'hi';
    if (clean.startsWith('es')) return 'es';
    if (clean.startsWith('de')) return 'de';
    if (clean.startsWith('fr')) return 'fr';
    if (clean.startsWith('pt')) return 'pt';
    if (clean.startsWith('ja')) return 'ja';
    if (clean.startsWith('zh')) return 'zh-CN';
    if (clean.startsWith('ar')) return 'ar';
    if (clean.startsWith('en')) return 'en';
  }

  return 'en';
}
